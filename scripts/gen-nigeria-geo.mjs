/**
 * Extracts Nigeria's real boundary (Natural Earth, via world-atlas) as GeoJSON
 * and writes it as a small typed module. Keeps the client bundle to just the
 * one country's geometry instead of the full world atlas.
 */
import { writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import * as topojson from 'topojson-client';
import world from 'world-atlas/countries-50m.json' with { type: 'json' };

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outFile = join(root, 'src', 'lib', 'nigeria-geo.ts');

const NIGERIA_NUMERIC_ID = '566';

const countries = topojson.feature(world, world.objects.countries);
const nigeria = countries.features.find((f) => f.id === NIGERIA_NUMERIC_ID);

if (!nigeria) {
  throw new Error('Nigeria feature not found in world-atlas countries-50m.json');
}

const contents = `// Generated by scripts/gen-nigeria-geo.mjs from world-atlas (Natural Earth data).
// Do not edit by hand; re-run the script if the source data changes.
import type { Feature, Geometry } from 'geojson';

export const nigeriaGeo: Feature<Geometry> = ${JSON.stringify(nigeria)};
`;

writeFileSync(outFile, contents);
console.log('nigeria-geo: wrote', outFile);
