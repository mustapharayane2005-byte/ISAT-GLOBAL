/**
 * Scans public/images for photo assets and writes a typed manifest.
 * PhotoSlot reads the manifest so it can render a real image when one has been
 * dropped in, and a labelled placeholder frame when it has not. Runs on predev
 * and prebuild, so adding a file to public/images is the only step needed.
 */
import { readdirSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const imagesDir = join(root, 'public', 'images');
const outFile = join(root, 'src', 'lib', 'photo-manifest.ts');

const EXTENSIONS = ['webp', 'avif', 'jpg', 'jpeg', 'png'];

if (!existsSync(imagesDir)) mkdirSync(imagesDir, { recursive: true });
mkdirSync(dirname(outFile), { recursive: true });

const found = new Map();
for (const file of readdirSync(imagesDir)) {
  const match = /^(.+)\.([a-z0-9]+)$/i.exec(file);
  if (!match) continue;
  const [, id, ext] = match;
  const extension = ext.toLowerCase();
  if (!EXTENSIONS.includes(extension)) continue;
  // Earlier extensions in the list win, so a .webp beats a stray .png.
  const current = found.get(id);
  if (current && EXTENSIONS.indexOf(current) <= EXTENSIONS.indexOf(extension)) continue;
  found.set(id, extension);
}

const entries = [...found.entries()]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([id, ext]) => `  '${id}': '/images/${id}.${ext}',`)
  .join('\n');

writeFileSync(
  outFile,
  `// Generated by scripts/gen-photo-manifest.mjs. Do not edit by hand.\n` +
    `export const photoManifest: Record<string, string> = {\n${entries}\n};\n`,
  'utf8',
);

console.log(`photo manifest: ${found.size} asset(s)`);
